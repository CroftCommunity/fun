// Extract the Blockdoku shape catalog verbatim from the original AGPL source and
// emit a compiled-in Rust `const` catalog for `blockdoku-core`.
//
// The catalog is GENERATED DATA — never hand-edit `shapes_gen.rs`. If a shape must
// change, change the reference (or an explicit patch here) and regenerate. This
// mirrors the kit rule for `shapes.json` ("generated data extracted from the
// original blocks.js; never hand-edit").
//
// Source of truth: reference/original/src/js/game/blocks.js -> BlockManager
//   defineBlockShapes(). That module is a standalone ES class with no imports, so
//   we import it and read the object directly rather than text-parsing.
//
// Usage: node tools/extract-blockdoku-shapes.mjs
// Writes: crates/blockdoku-core/src/shapes_gen.rs
//
// Tier classification (faithful to generateRandomBlocks):
//   isMagic -> Magic ; isWild -> Wild ; otherwise -> Standard.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const refBlocks = join(root, "reference/original/src/js/game/blocks.js");
const outFile = join(root, "crates/blockdoku-core/src/shapes_gen.rs");

const { BlockManager } = await import(pathToFileURL(refBlocks).href).catch((e) => {
  console.error(
    `\nCannot import the reference blocks.js at:\n  ${refBlocks}\n` +
      `Clone the original first (read-only reference):\n` +
      `  git clone --depth 1 https://github.com/chasemp/blockdoku reference/original\n`,
  );
  throw e;
});

const shapes = new BlockManager().defineBlockShapes();

// Deterministic order = object insertion order (matches the source file top-to-bottom).
const keys = Object.keys(shapes);

function tierOf(s) {
  if (s.isMagic) return "Magic";
  if (s.isWild) return "Wild";
  return "Standard";
}

function matrixLiteral(shape) {
  // shape is number[][] of 0/1. Emit as &[&[u8]].
  const rows = shape.map((row) => `&[${row.map((c) => (c ? 1 : 0)).join(", ")}]`);
  return `&[${rows.join(", ")}]`;
}

const entries = keys.map((key) => {
  const s = shapes[key];
  const tier = tierOf(s);
  const magicType = s.isMagic ? `Some("${s.magicType}")` : "None";
  return (
    `    ShapeDef {\n` +
    `        key: "${key}",\n` +
    `        name: ${JSON.stringify(s.name)},\n` +
    `        tier: Tier::${tier},\n` +
    `        points: ${s.points},\n` +
    `        magic_type: ${magicType},\n` +
    `        cells: ${matrixLiteral(s.shape)},\n` +
    `    },`
  );
});

const counts = { Standard: 0, Wild: 0, Magic: 0 };
for (const key of keys) counts[tierOf(shapes[key])]++;

const header = `//! GENERATED by \`tools/extract-blockdoku-shapes.mjs\` — DO NOT EDIT.
//!
//! The Blockdoku shape catalog, extracted verbatim from the original AGPL source
//! (\`reference/original/src/js/game/blocks.js\`, \`BlockManager::defineBlockShapes\`).
//! ${keys.length} shapes: ${counts.Standard} standard, ${counts.Wild} wild, ${counts.Magic} magic.
//! Colours are cosmetic and intentionally omitted (off the hashed path).
//!
//! \`rustfmt::skip\` keeps this file byte-stable across regenerations so
//! \`cargo fmt --check\` never fights the generator.

use crate::shapes::{ShapeDef, Tier};

/// The full catalog, in source order.
#[rustfmt::skip]
pub const CATALOG: &[ShapeDef] = &[
${entries.join("\n")}
];
`;

await writeFile(outFile, header, "utf8");
console.error(
  `wrote ${outFile}\n  ${keys.length} shapes: ${counts.Standard} standard, ${counts.Wild} wild, ${counts.Magic} magic`,
);
